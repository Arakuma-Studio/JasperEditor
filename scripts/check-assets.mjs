#!/usr/bin/env node
// Asset attribution lint (AGENTS.md §3, ARCHITECTURE D-38). Run by `pnpm lint`.
//
// Every non-code asset in the repository (images, icons, screenshots, fonts, LUTs, media, ML weights,
// WebAssembly binaries, project fixtures…; `ASSET_EXTENSIONS`) needs:
//   1. a sidecar `<file>.attribution` next to it with the keys of `REQUIRED_KEYS`, a recognised licence and an
//      existing licence file when one is named;
//   2. a row in ATTRIBUTION.md that names the file's repo path in backticks.
// Also fails on: sidecars whose asset is gone, sidecars whose `asset:` is not the file's name, and anything
// committed under `fixtures/media/` (generated by `pnpm fixtures`, never committed).
//
// Files checked: tracked files plus new untracked files that are not gitignored (`git ls-files --cached
// --others --exclude-standard`), so an asset fails the lint before it is committed. Gitignored paths
// (node_modules, vendor/, .reference/, fixtures/media/, build output) are never listed or opened.
import { spawnSync } from 'node:child_process';
import { existsSync, readFileSync } from 'node:fs';
import { basename, dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

