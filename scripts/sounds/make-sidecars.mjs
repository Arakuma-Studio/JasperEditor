#!/usr/bin/env node
// Writes the `.attribution` sidecar of every starter-kit sound and its ATTRIBUTION.md row (AGENTS.md §3; spec 12 §0
// decision 1, P1-R4), from apps/engine/sounds/starter/manifest.json (what the engine indexes) and
// scripts/sounds/starter-selection.json (source files and derivations). Run after `curate-starter.ts build`.
//
//   node scripts/sounds/make-sidecars.mjs          write the sidecars and the ATTRIBUTION.md section
//   node scripts/sounds/make-sidecars.mjs --check  exit 1 when anything is missing or out of date
//
// A sidecar's `added:` line is kept when the sidecar already exists, so re-running does not change history.
import { existsSync, readdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..', '..');
export const STARTER_REL = 'apps/engine/sounds/starter';
const STARTER = join(ROOT, STARTER_REL);
const SELECTION = join(ROOT, 'scripts', 'sounds', 'starter-selection.json');
const ATTRIBUTION = join(ROOT, 'ATTRIBUTION.md');
export const BEGIN = '<!-- starter-kit:begin (generated by scripts/sounds/make-sidecars.mjs) -->';
export const END = '<!-- starter-kit:end -->';
const CONTRIBUTOR = 'sound-design WP1.2b (starter kit)';

const today = () => new Date().toISOString().slice(0, 10);

/** The sidecar text of one manifest sound. Pure, for tests. */
export function sidecarText(sound, pack, sel, added) {
	const derived = sel.filter
		? `Derived from Kenney's CC0 recording(s) ${sel.src.map((f) => `Audio/${f}`).join(', ')}: ${sel.derivation}.`
		: `Kenney's CC0 recording Audio/${sel.src[0]}, unedited.`;
	const notes = [
		`From the pack "${pack.title}" (archive ${pack.url}, sha256 ${pack.sha256}).`,
		derived,
		'Converted to 48 kHz OGG Vorbis (libvorbis q5, LGPL FFmpeg) by scripts/sounds/curate-starter.ts;',
		`types ${sound.types.join(', ')}, chosen by measurement (judge of @jasper/audio-fx accepts it as ${sound.types[0]}).`,
		'The pack page states the licence (Creative Commons CC0) and the archive holds License.txt saying',
		'"License: (Creative Commons Zero, CC0)"; credit to Kenney is welcome but not required.',
	];
	return [
		`asset:        ${sound.file.split('/').pop()}`,
		`title:        ${sound.title} (sound effect, Kenney "${pack.title.replace(/ \(Kenney\)$/, '')}")`,
		`author:       ${sound.author}`,
		`source:       ${sound.sourceUrl}`,
		`license:      ${sound.license}`,
		'license-file: none',
		`added:        ${added}`,
		`notes:        ${notes[0]}`,
		...notes.slice(1).map((n) => `              ${n}`),
		'',
	].join('\n');
}

/** The generated ATTRIBUTION.md section (between the markers). Pure, for tests. */
export function attributionSection(manifest) {
	return [
		BEGIN,
		'',
		'## Sound effects (starter kit)',
		'',
		`The bundled sound library starter kit (\`${STARTER_REL}/\`, spec 12 §0 decision 1): sounds from Kenney's CC0 audio`,
		'packs, some derived (reversed, pitched, layered, faded); each sidecar names the pack archive, its sha256, the',
		'source file(s) and the derivation. Credit to Kenney is not required by CC0 but given here.',
		'',
		'| Asset | Author | Source | Licence |',
		'|---|---|---|---|',
		...manifest.sounds.map(
			(s) => `| \`${STARTER_REL}/${s.file}\` | ${s.author} | ${s.sourceUrl} | ${s.license} |`,
		),
		'',
		END,
	].join('\n');
}

/** ATTRIBUTION.md with the section replaced (or appended). Pure, for tests. */
export function withSection(text, section) {
	const a = text.indexOf(BEGIN);
	const b = text.indexOf(END);
	if (a >= 0 && b > a) return `${text.slice(0, a)}${section}${text.slice(b + END.length)}`;
	return `${text.replace(/\n*$/, '\n\n')}${section}\n`;
}

/**
 * Brings the sidecars and the ATTRIBUTION.md section in line with the manifest (`write`) or only lists what is
 * missing or stale (`write: false`). Returns the problems (empty = up to date).
 */
export function syncSidecars({ write }) {
	const check = !write;
	const manifest = JSON.parse(readFileSync(join(STARTER, 'manifest.json'), 'utf8'));
	const selection = JSON.parse(readFileSync(SELECTION, 'utf8'));
	const packs = new Map(manifest.packs.map((p) => [p.id, p]));
	const picks = new Map(selection.sounds.map((s) => [s.file, s]));
	const problems = [];
	for (const sound of manifest.sounds) {
		const pack = packs.get(sound.packId);
		const sel = picks.get(sound.file);
		if (!pack || !sel) {
			problems.push(`${sound.file}: no pack or selection entry`);
			continue;
		}
		const path = join(STARTER, `${sound.file}.attribution`);
		const old = existsSync(path) ? readFileSync(path, 'utf8') : null;
		const added = /^added:\s*(.+)$/m.exec(old ?? '')?.[1]?.trim() ?? `${today()} by ${CONTRIBUTOR}`;
		const text = sidecarText(sound, pack, sel, added);
		if (old !== text) {
			if (check) problems.push(`${STARTER_REL}/${sound.file}.attribution is missing or out of date`);
			else writeFileSync(path, text);
		}
	}
	const attribution = readFileSync(ATTRIBUTION, 'utf8');
	const next = withSection(attribution, attributionSection(manifest));
	if (next !== attribution) {
		if (check) problems.push('ATTRIBUTION.md starter-kit section is out of date');
		else writeFileSync(ATTRIBUTION, next);
	}
	// Sidecars of sounds no longer in the kit (`curate-starter.ts build` removes their audio).
	const listed = new Set(manifest.sounds.map((s) => `${s.file}.attribution`));
	for (const f of readdirSync(STARTER))
		if (f.endsWith('.attribution') && !listed.has(f)) {
			if (check) problems.push(`${STARTER_REL}/${f} has no sound in the manifest`);
			else rmSync(join(STARTER, f));
		}
	return { problems, count: manifest.sounds.length };
}

function main() {
	const check = process.argv.includes('--check');
	const { problems, count } = syncSidecars({ write: !check });
	if (problems.length) {
		for (const p of problems) console.error(p);
		console.error('make-sidecars: run `node scripts/sounds/make-sidecars.mjs`');
		process.exit(1);
	}
	console.log(`make-sidecars: ${count} sidecars and ATTRIBUTION.md ${check ? 'up to date' : 'written'}`);
}

const isMain = process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1];
if (isMain) main();
