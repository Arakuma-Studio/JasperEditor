// WP6.5b carry-over (wp-note "Limits (after this pass)"): sounds over 120 s (`LIBRARY_PAD_MAX_SECONDS`) were registered
// as they are. A lossy one seeked by an In point (every export path decodes a clip from its In point) played up to 128
// samples late (ffmpeg's seeked Vorbis decode vs its full decode, which the descriptors are measured on), and none got
// lead silence, so a peak between frames played up to one frame late. Registration now copies sounds up to
// `LIBRARY_PAD_MAX_SECONDS` (1 h), streamed by ffmpeg file to file, with a byte cap and a free-disk check; beyond them the
// sound is registered as it is and the response says why (`inexact`).
//
// The long sound here is a real library sound (a user folder, indexed), an Ogg Vorbis file generated by ffmpeg in the
// test: a quiet noise bed from its first sample (no quiet head) with a loud click at 7.3 s, 125 s long.
import { execFileSync } from 'node:child_process';
import { mkdirSync, readdirSync } from 'node:fs';
import { readFile, rm } from 'node:fs/promises';
import { join } from 'node:path';
import { type EngineJob, RegisterSoundResponseSchema, type SoundEntry } from '@jasper/api';
import { appdirPaths } from '@jasper/config';
import {
	FLICKS_PER_SECOND,
	frameToSample,
	LIBRARY_LEAD_SILENCE_SEC,
	LIBRARY_PAD_MAX_SECONDS,
	type Sequence,
} from '@jasper/project';
import { afterAll, beforeAll, describe, expect, it } from 'vitest';
import { renderMixdown, WAV_F32_HEADER_BYTES } from '../src/audio/mixdown.ts';
import { audioWorld } from '../src/sound-design/bed.ts';
import { coreServices } from '../src/tools/services.ts';
import {
	closeApps,
	DocBuilder,
	H,
	JSON_H,
	makeApp,
	TEST_FFMPEG,
	TEST_FFPROBE,
	tempAppdir,
} from './helpers.ts';
import { makeStarter } from './sound-fixtures.ts';

const SR = 48_000;
const LONG_SEC = 125;
const CLICK_SEC = 7.3;
const ENV_KEYS = [
	'JASPER_SOUND_STARTER_DIR',
	'JASPER_SOUND_SYNTH_VARIANTS',
	'JASPER_SOUND_AUTO_INDEX',
	'JASPER_SOUND_COPY_MAX_BYTES',
	'JASPER_SOUND_COPY_RESERVE_BYTES',
] as const;
const saved = Object.fromEntries(ENV_KEYS.map((k) => [k, process.env[k]]));

/** A Vorbis encoder of this ffmpeg: libvorbis (BSD) when built in, else ffmpeg's own (LGPL, experimental). */
function vorbisArgs(): string[] {
	const list = execFileSync(TEST_FFMPEG, ['-hide_banner', '-encoders']).toString();
	return /\blibvorbis\b/.test(list)
		? ['-c:a', 'libvorbis', '-q:a', '4']
		: ['-c:a', 'vorbis', '-strict', '-2'];
}

/** Interleaved f32 samples of a file's first audio stream (all of it), as ffmpeg decodes it. */
function decodeF32(file: string, seekSec?: number, seconds?: number): Float32Array {
	const out = execFileSync(
		TEST_FFMPEG,
		[
			'-v',
			'error',
			...(seekSec !== undefined ? ['-ss', seekSec.toFixed(9)] : []),
			...(seconds !== undefined ? ['-t', String(seconds)] : []),
			'-i',
			file,
			'-map',
			'0:a:0',
			'-f',
			'f32le',
			'-',
		],
		{ maxBuffer: 256 * 1024 * 1024 },
	);
	return new Float32Array(out.buffer.slice(out.byteOffset, out.byteOffset + out.byteLength));
}

function codecOf(file: string): string {
	return execFileSync(TEST_FFPROBE, [
		'-v',
		'error',
		'-select_streams',
		'a:0',
		'-show_entries',
		'stream=codec_name',
		'-of',
		'csv=p=0',
		file,
	])
		.toString()
		.trim();
}

let app: Awaited<ReturnType<typeof makeApp>>;
let folder = '';
let projectId = '';
let longOgg = '';

beforeAll(async () => {
	process.env.JASPER_SOUND_STARTER_DIR = makeStarter(tempAppdir('jasper-long-starter-'));
	process.env.JASPER_SOUND_SYNTH_VARIANTS = '0';
	process.env.JASPER_SOUND_AUTO_INDEX = '0';
	delete process.env.JASPER_SOUND_COPY_MAX_BYTES;
	delete process.env.JASPER_SOUND_COPY_RESERVE_BYTES;
	app = await makeApp();
	folder = tempAppdir('jasper-long-sfx-');
	mkdirSync(join(folder, 'Beds'), { recursive: true });
	longOgg = join(folder, 'Beds', 'long bed.ogg');
	// −40 dBFS pink noise from the first sample, a 20 ms 0 dBFS-ish click at 7.3 s; mono 48 kHz
	execFileSync(TEST_FFMPEG, [
		'-v',
		'error',
		'-y',
		'-f',
		'lavfi',
		'-i',
		`anoisesrc=d=${LONG_SEC}:c=pink:r=${SR}:a=0.01:s=3`,
		'-f',
		'lavfi',
		'-i',
		`sine=f=1500:r=${SR}:d=0.02`,
		'-filter_complex',
		`[1:a]volume=0.9,adelay=${Math.round(CLICK_SEC * 1000)}:all=1,apad[c];[0:a][c]amix=inputs=2:duration=first:normalize=0,aformat=sample_rates=${SR}:channel_layouts=mono[o]`,
		'-map',
		'[o]',
		...vorbisArgs(),
		longOgg,
	]);
	const put = await app.inject({
		method: 'PUT',
		url: '/api/sounds/roots',
		headers: JSON_H,
		payload: { roots: [{ path: folder, license: 'CC0-1.0' }] },
	});
	expect(put.statusCode, put.body).toBe(200);
	const job = await coreServices(app).queue.wait((put.json() as { job: EngineJob }).job.id);
	expect(job.state, JSON.stringify(job.error)).toBe('succeeded');
	const created = await app.inject({
		method: 'POST',
		url: '/api/projects',
		headers: JSON_H,
		payload: { name: 'Long', preset: 'hd-1080p-30' },
	});
	projectId = (created.json() as { projectId: string }).projectId;
}, 600_000);

afterAll(async () => {
	await closeApps();
	for (const k of ENV_KEYS) {
		if (saved[k] === undefined) delete process.env[k];
		else process.env[k] = saved[k];
	}
});

async function longSound(): Promise<SoundEntry> {
	const r = await app.inject({ method: 'GET', url: '/api/sounds?sources=folder&limit=50', headers: H });
	const hit = (r.json() as { results: { sound: SoundEntry }[] }).results.find(
		(x) => x.sound.title === 'long bed',
	);
	if (!hit) throw new Error('no long bed');
	return hit.sound;
}

async function registerSound(id: string, project = projectId) {
	const r = await app.inject({
		method: 'POST',
		url: `/api/sounds/${id}/register`,
		headers: JSON_H,
		payload: { projectId: project },
	});
	expect(r.statusCode, r.body).toBe(200);
	return RegisterSoundResponseSchema.parse(r.json());
}

describe('sounds longer than 120 s are registered sample-exact', { timeout: 600_000 }, () => {
	it('a 125 s Ogg Vorbis sound: a PCM copy with lead silence, seek-exact at an In point, peak exactly on the frame', async () => {
		expect(LONG_SEC).toBeGreaterThan(120);
		const e = await longSound();
		expect(e.descriptors.durationSec).toBeGreaterThan(120);
		expect(e.descriptors.headQuietSec).toBeLessThan(LIBRARY_LEAD_SILENCE_SEC);
		expect(e.descriptors.durationSec).toBeLessThanOrEqual(LIBRARY_PAD_MAX_SECONDS);
		const reg = await registerSound(e.id);
		// a managed PCM copy, not the Ogg itself
		expect(reg.fingerprint).not.toBe(e.fingerprint);
		expect(reg.inexact).toBeUndefined();
		expect(reg.library.inexact).toBeUndefined();
		expect(reg.library.leadSilenceSec).toBe(LIBRARY_LEAD_SILENCE_SEC);
		const copy = join(appdirPaths(app.appdir).mediaDir, reg.mediaKey, 'long bed.wav');
		expect(readdirSync(join(appdirPaths(app.appdir).mediaDir, reg.mediaKey))).toEqual(['long bed.wav']);
		expect(codecOf(copy)).toBe('pcm_f32le');
		const lead = Math.round(LIBRARY_LEAD_SILENCE_SEC * SR);

		// placed peak-aligned on a cue: the sub-frame rest comes out of the lead silence
		const b = new DocBuilder('hd-1080p-30', 700);
		const { mediaKey: _k, browserPlayable: _b, library, existingMediaId: _x, inexact: _i, ...asset } = reg;
		const r0 = b.tx([{ type: 'media.register', asset: { ...asset, derivation: null, library } }]);
		const mediaId = (r0.results[0] as { mediaId: string }).mediaId;
		const cue = 400; // 13.33 s: the click at 7.3 s puts the clip's start at ≈ 6 s
		const r = b.tx([
			{
				type: 'soundCue.add',
				cues: [{ frame: cue, kind: 'cut', weight: 'support', source: 'user', align: 'peak', ref: '$c' }],
			},
			{ type: 'soundDesign.place', cueId: '$c', layers: [{ mediaId, gainDb: 0 }] },
		]);
		const placed = (
			r.results[1] as { clips: { clipId: string; errorFlicks: number; sourceInFlicks: number }[] }
		).clips[0]!;
		expect(placed.errorFlicks).toBe(0);
		expect(placed.sourceInFlicks).toBeGreaterThan(0);
		// the clip starts with the bed (In point inside the lead): trim its head by 3 s so it is seeked into the bed
		b.tx([{ type: 'clip.trim', clipId: placed.clipId, edge: 'in', deltaFrames: 90 }]);
		const trimmed = b.doc.sequences[b.seqId]!.clips[placed.clipId]!;
		expect(trimmed.sourceIn).toBe(placed.sourceInFlicks + 90 * (FLICKS_PER_SECOND / 30));
		const inSample = (trimmed.sourceIn * SR) / FLICKS_PER_SECOND;
		expect(inSample).toBeGreaterThan(3 * SR);

		// the In-point decode every export path does (ffmpeg input seek) is the full decode, sample for sample
		const full = decodeF32(longOgg);
		const at = Math.round(inSample);
		const seeked = decodeF32(copy, at / SR, 3);
		expect(seeked.length).toBe(3 * SR);
		const want = full.subarray(at - lead, at - lead + 3 * SR);
		expect(Buffer.from(seeked.buffer).equals(Buffer.from(want.slice().buffer))).toBe(true);
		// …and the copy as a whole is the lead silence, then the full decode bit for bit
		const whole = decodeF32(copy);
		expect(whole.subarray(0, lead).every((v) => v === 0)).toBe(true);
		expect(
			Buffer.from(whole.subarray(lead, lead + full.length).slice().buffer).equals(
				Buffer.from(full.slice().buffer),
			),
		).toBe(true);

		// the engine's mixer renders the click's peak on the cue frame's sample
		const fps = (b.doc.sequences[b.seqId] as Sequence).settings.frameRate;
		const world = await audioWorld(b.doc, b.seqId, coreServices(app).registry);
		const scratch = tempAppdir('jasper-long-render-');
		const out = await renderMixdown({
			ff: coreServices(app).ffmpeg,
			snapshot: world.snapshot,
			media: world.media,
			range: { start: cue - 15, end: cue + 15 },
			outputLayout: 'stereo',
			scratchDir: scratch,
			withoutLoudness: true,
		});
		const buf = await readFile(out.path!);
		const pcm = new Float32Array(buf.buffer.slice(buf.byteOffset + WAV_F32_HEADER_BYTES));
		await rm(scratch, { recursive: true, force: true });
		let best = -1;
		let bestAbs = -1;
		for (let i = 0; i < pcm.length / 2; i++)
			if (Math.abs(pcm[i * 2]!) > bestAbs) {
				bestAbs = Math.abs(pcm[i * 2]!);
				best = i;
			}
		// where the source's loudest sample must play: its place in the copy (after the lead), through the clip's In point
		const sourcePeak = full.reduce((m, v, i) => (Math.abs(v) > Math.abs(full[m]!) ? i : m), 0);
		const clip = b.doc.sequences[b.seqId]!.clips[placed.clipId]! as typeof trimmed & {
			sfx?: { placement: { peakFlicks: number } };
		};
		const F = FLICKS_PER_SECOND / (fps.num / fps.den);
		const expected =
			((clip.start - (cue - 15)) * F + ((sourcePeak + lead) / SR) * FLICKS_PER_SECOND - clip.sourceIn) *
			(SR / FLICKS_PER_SECOND);
		expect(Math.abs(best - expected), `rendered peak at ${best}, expected ${expected}`).toBeLessThanOrEqual(
			0.5,
		);
		// the aligned point (the descriptors' peak, errorFlicks 0) plays on the cue frame's first sample exactly
		const cueAt = frameToSample(cue, fps, SR) - frameToSample(cue - 15, fps, SR);
		const alignedInCopy = (clip.sfx!.placement.peakFlicks * SR) / FLICKS_PER_SECOND;
		expect(Math.abs(expected - (cueAt + (sourcePeak + lead - alignedInCopy)))).toBeLessThan(1e-6);
	});

	it('registration stays deterministic: the same sound again, or into another project, is the same copy', async () => {
		const e = await longSound();
		const a = await registerSound(e.id);
		const b = await registerSound(e.id);
		expect(b.fingerprint).toBe(a.fingerprint);
		const created = await app.inject({
			method: 'POST',
			url: '/api/projects',
			headers: JSON_H,
			payload: { name: 'Long 2', preset: 'hd-1080p-30' },
		});
		const other = (created.json() as { projectId: string }).projectId;
		expect((await registerSound(e.id, other)).mediaKey).toBe(a.mediaKey);
	});

	it('over the byte cap or without the free disk space, the sound is registered as it is and the response says why', async () => {
		const e = await longSound();
		process.env.JASPER_SOUND_COPY_MAX_BYTES = String(1024 * 1024);
		try {
			const big = await registerSound(e.id);
			expect(big.fingerprint).toBe(e.fingerprint);
			expect(big.library.leadSilenceSec).toBeUndefined();
			expect(big.inexact?.reason).toBe('too-large');
			expect(big.inexact?.message).toMatch(/MB/);
			// the numbers for the editor's notice, and the reason kept in the provenance the media is registered with
			expect(big.inexact?.maxBytes).toBe(1024 * 1024);
			expect(big.inexact!.bytes!).toBeGreaterThan(1024 * 1024);
			expect(big.library.inexact).toEqual({ reason: 'too-large' });
		} finally {
			delete process.env.JASPER_SOUND_COPY_MAX_BYTES;
		}
		process.env.JASPER_SOUND_COPY_RESERVE_BYTES = String(2 ** 52);
		try {
			const full = await registerSound(e.id);
			expect(full.fingerprint).toBe(e.fingerprint);
			expect(full.inexact?.reason).toBe('disk-space');
			expect(full.inexact!.bytes!).toBeGreaterThan(0);
			expect(full.inexact!.freeBytes!).toBeGreaterThanOrEqual(0);
			expect(full.library.inexact).toEqual({ reason: 'disk-space' });
		} finally {
			delete process.env.JASPER_SOUND_COPY_RESERVE_BYTES;
		}
	});
});
