/** Glyph bitmaps (row-major, GLYPH_WIDTH × GLYPH_HEIGHT, 1 = ink), built once. */
const BITMAPS = new Map<string, Uint8Array>(
	Object.entries(G).map(([ch, rows]) => {
		const bits = new Uint8Array(GLYPH_WIDTH * GLYPH_HEIGHT);
		rows.split(' ').forEach((row, y) => {
			for (let x = 0; x < GLYPH_WIDTH; x++) bits[y * GLYPH_WIDTH + x] = row[x] === '#' ? 1 : 0;
		});
		return [ch, bits];
	}),
);

const FOLD: Record<string, string> = {
	'–': '-',
	'—': '-',
	'−': '-',
	'‘': "'",
	'’': "'",
	'“': '"',
	'”': '"',
	'…': '...',
	'×': 'x',
	'·': '.',
	'→': '>',
	µ: 'u',
	ß: 'ss',
};

/** The text as the font can draw it: accents dropped, typographic punctuation folded, the rest "?". */
export function foldText(text: string): string {
	let out = '';
	for (const ch of text.normalize('NFKD').replace(/[̀-ͯ]/g, '')) {
		if (BITMAPS.has(ch)) out += ch;
		else if (FOLD[ch]) out += FOLD[ch];
		else if (/\s/.test(ch)) out += ' ';
		else out += '?';
	}
	return out;
}

/** Width in pixels of `text` drawn at `scale` (the advance of every character, minus the trailing gap). */
export function textWidth(text: string, scale = 1): number {
	const n = foldText(text).length;
	return n ? (n * GLYPH_ADVANCE - 1) * scale : 0;
}

/** Characters of `text` that fit `maxWidth` px at `scale`; longer text is cut and ends with "..". */
export function fitText(text: string, maxWidth: number, scale = 1): string {
	const t = foldText(text);
	const max = Math.floor((maxWidth / scale + 1) / GLYPH_ADVANCE);
	if (t.length <= max) return t;
	return max <= 2 ? t.slice(0, Math.max(0, max)) : `${t.slice(0, max - 2)}..`;
}

type Canvas = { width: number; height: number; data: Uint8Array };

/** Draws `text` with its top-left corner at (x, y) in an RGBA canvas (clipped to it). */
export function drawText(
	img: Canvas,
	text: string,
	x: number,
	y: number,
	color: readonly [number, number, number],
	scale = 1,
): void {
	let cx = Math.round(x);
	const top = Math.round(y);
	for (const ch of foldText(text)) {
		const bits = BITMAPS.get(ch) ?? BITMAPS.get('?')!;
		for (let gy = 0; gy < GLYPH_HEIGHT; gy++)
			for (let gx = 0; gx < GLYPH_WIDTH; gx++) {
				if (!bits[gy * GLYPH_WIDTH + gx]) continue;
				for (let sy = 0; sy < scale; sy++)
					for (let sx = 0; sx < scale; sx++) {
						const px = cx + gx * scale + sx;
						const py = top + gy * scale + sy;
						if (px < 0 || py < 0 || px >= img.width || py >= img.height) continue;
						const o = (py * img.width + px) * 4;
						img.data[o] = color[0];
						img.data[o + 1] = color[1];
						img.data[o + 2] = color[2];
						img.data[o + 3] = 255;
					}
			}
		cx += GLYPH_ADVANCE * scale;
	}
}
