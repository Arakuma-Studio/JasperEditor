// Build-time pieces of `/editor-boot.js`, used by vite.config.ts.
/**
 * `/editor-boot.js` is a small classic script that index.html loads
 * before the bundle (external, so a strict CSP `script-src 'self'` works). On an editor URL (`/project/<id>`) it
 *   - preloads the editor's chunks (the shell, the dock and every panel body), which the bundle would otherwise
 *     discover in three round trips after it has run: they download and compile while the main bundle does;
 *   - starts fetching the project file at once (`window.__jasperEarly`, taken by the engine client's first matching
 *     request, state/engine.tsx), instead of after the bundle has booted.
 * The build writes the chunk list; the dev server serves the script with an empty list.
 *
 * On every URL it also watches the entry module: when the bundle or one of its static imports cannot be downloaded
 * (the network changed while the page loaded, the server restarted), nothing runs and nothing reports it; the page
 * would stay blank. The script first reloads the page with a short backoff because the common cause is transient —
 * Chromium aborts every request in flight, loopback included, when it sees the host's IP addresses change
 * (`net::ERR_NETWORK_CHANGED`; on Linux any interface counts, so a Docker container starting or stopping is enough),
 * and a slow first load (a cold dev server transforming hundreds of modules, a loaded machine, the desktop shell
 * starting) stays in flight long enough to be affected.
 * A load that failed quickly (the server is down or broken) is retried BOOT_RETRIES times; one that failed after
 * BOOT_SLOW_MS was making progress and was cut off, and only counts towards BOOT_MAX_RELOADS per tab, since every
 * reload is faster than the one before (the server's transforms and the browser cache are warm). Only when the
 * reloads fail too does it show a message with a Reload button. (A lazy chunk that fails is reported by the app
 * itself: "Could not load the editor".)
 */
export const EDITOR_BOOT = 'editor-boot.js';
/** Automatic reloads of a page whose bundle failed to load quickly, before the message is shown (per tab). */
const BOOT_RETRIES = 3;
/** A load that failed later than this after the navigation was cut off while making progress (a slow first load). */
const BOOT_SLOW_MS = 8000;
/** Automatic reloads per tab in all, slow ones included. */
const BOOT_MAX_RELOADS = 8;
/** sessionStorage: `{ fast, total }`, the reloads so far; cleared once the app renders. */
const BOOT_RETRY_KEY = 'jasper:boot-retries';

/** The texts of the start-up failure message; the bundle and its catalogue are what failed to load. */
const BOOT_FAILURE_TEXT: Record<string, { message: string; reload: string }> = {
	en: { message: 'JasperEditor could not load. Check your connection and reload.', reload: 'Reload' },
	es: {
		message: 'No se pudo cargar JasperEditor. Comprueba la conexión y vuelve a cargar.',
		reload: 'Recargar',
	},
};

export function editorBootScript(chunks: readonly string[]): string {
	return `// Generated by apps/web/vite.config.ts (editorBoot). Reports a bundle that could not load; preloads the editor
// and starts fetching the project.
(() => {
	const texts = ${JSON.stringify(BOOT_FAILURE_TEXT)};
	const KEY = ${JSON.stringify(BOOT_RETRY_KEY)};
	const store = (n) => {
		try {
			if (n) sessionStorage.setItem(KEY, JSON.stringify(n));
			else sessionStorage.removeItem(KEY);
		} catch {}
	};
	const count = (v) => (Number.isSafeInteger(v) && v > 0 ? v : 0);
	let tries = { fast: 0, total: 0 };
	try {
		const saved = JSON.parse(sessionStorage.getItem(KEY) || '{}') || {};
		tries = { fast: count(saved.fast), total: count(saved.total) };
	} catch {}
	let retrying = false;
	// The app rendered: a later failure starts with a full set of retries again.
	const watch = () => {
		const root = document.getElementById('root');
		if (!root || typeof MutationObserver === 'undefined') return;
		new MutationObserver((_m, observer) => {
			if (root.childElementCount > 0 && !root.querySelector('[data-testid="app-load-error"]')) {
				store(null);
				observer.disconnect();
			}
		}).observe(root, { childList: true });
	};
	if (tries.total) {
		if (document.readyState === 'loading') document.addEventListener('DOMContentLoaded', watch, { once: true });
		else watch();
	}
	window.addEventListener(
		'error',
		(event) => {
			const el = event.target;
			if (!el || el.tagName !== 'SCRIPT' || el.type !== 'module') return;
			const root = document.getElementById('root');
			if (!root || root.childElementCount > 0 || retrying) return;
			const slow = typeof performance !== 'undefined' && performance.now() >= ${BOOT_SLOW_MS};
			const fast = tries.fast + (slow ? 0 : 1);
			if (fast <= ${BOOT_RETRIES} && tries.total < ${BOOT_MAX_RELOADS}) {
				// Every module of the page fails at once: one reload.
				retrying = true;
				const total = tries.total + 1;
				store({ fast, total });
				setTimeout(() => location.reload(), Math.min(300 * total, 2000));
				return;
			}
			let lang = 'en';
			try {
				lang = String(JSON.parse(localStorage.getItem('jasper:gaps-prefs') || '{}').appearance.language).slice(0, 2);
			} catch {}
			const text = texts[lang] || texts.en;
			const box = document.createElement('div');
			box.setAttribute('role', 'alert');
			box.setAttribute('data-testid', 'app-load-error');
			box.className = 'flex h-full flex-col items-center justify-center gap-3 bg-pr-app text-pr-muted';
			const message = document.createElement('p');
			message.textContent = text.message;
			const reload = document.createElement('button');
			reload.type = 'button';
			reload.textContent = text.reload;
			reload.addEventListener('click', () => {
				store(null);
				location.reload();
			});
			box.append(message, reload);
			root.appendChild(box);
			reload.focus();
		},
		true,
	);
})();
(() => {
	const m = /^\\/project\\/([^/?#]+)/.exec(location.pathname);
	if (!m || m[1] === 'demo') return;
	for (const href of ${JSON.stringify(chunks)}) {
		const link = document.createElement('link');
		link.rel = 'modulepreload';
		link.href = href;
		document.head.appendChild(link);
	}
	let id;
	try {
		id = decodeURIComponent(m[1]);
	} catch {
		return;
	}
	const url = '/api/projects/' + encodeURIComponent(id);
	let response;
	try {
		response = fetch(url, { headers: { accept: 'application/json' } });
	} catch {
		return;
	}
	response.catch(() => undefined);
	window.__jasperEarly = { url, response, at: Date.now() };
})();
`;
}

export type BundleChunk = {
	type: string;
	fileName: string;
	facadeModuleId?: string | null;
	isEntry?: boolean;
	isDynamicEntry?: boolean;
	imports?: string[];
};

function staticClosure(start: BundleChunk[], byFile: Map<string, BundleChunk>): Set<string> {
	const seen = new Set<string>();
	const walk = (c: BundleChunk | undefined) => {
		if (!c || seen.has(c.fileName)) return;
		seen.add(c.fileName);
		for (const f of c.imports ?? []) walk(byFile.get(f));
	};
	for (const c of start) walk(c);
	return seen;
}

/** On-demand runtimes and their static imports, warmed by the service worker after the page has loaded. */
export function optionalEditorChunks(bundle: Record<string, BundleChunk>): string[] {
	const chunks = Object.values(bundle).filter((c) => c.type === 'chunk');
	const byFile = new Map(chunks.map((c) => [c.fileName, c]));
	const optional = chunks.filter((c) =>
		/\/vendor-(pdf|quickjs|lottie|screenshot)-[^/]+\.js$/.test(c.fileName),
	);
	return [...staticClosure(optional, byFile)]
		.filter((f) => f.endsWith('.js'))
		.sort()
		.map((f) => `/${f}`);
}

/** The chunks an editor URL needs beyond the entry's own: the shell, the panel bodies and what they import. */
export function editorChunks(bundle: Record<string, BundleChunk>): string[] {
	const chunks = Object.values(bundle).filter((c) => c.type === 'chunk');
	const byFile = new Map(chunks.map((c) => [c.fileName, c]));
	const norm = (id: string | null | undefined) => (id ?? '').replace(/\\/g, '/');
	const loaded = staticClosure(
		chunks.filter((c) => c.isEntry),
		byFile,
	);
	const editor = chunks.filter(
		(c) =>
			c.isDynamicEntry &&
			(/\/src\/shell\/EditorShell\.tsx$/.test(norm(c.facadeModuleId)) ||
				/\/src\/panels\/[^/]+\/[^/]+\.tsx$/.test(norm(c.facadeModuleId))),
	);
	return [...staticClosure(editor, byFile)]
		.filter((f) => !loaded.has(f) && f.endsWith('.js'))
		.sort()
		.map((f) => `/${f}`);
}
