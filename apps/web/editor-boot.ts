// Build-time pieces of `/editor-boot.js` (used by vite.config.ts; kept apart so tests can import them).
/**
 * polish (project open, docs/performance.md §6): `/editor-boot.js`, a small classic script that index.html loads
 * before the bundle (external, so a strict CSP `script-src 'self'` works). On an editor URL (`/project/<id>`) it
 *   - preloads the editor's chunks (the shell, the dock and every panel body), which the bundle would otherwise
 *     discover in three round trips after it has run: they download and compile while the main bundle does;
 *   - starts fetching the project file at once (`window.__jasperEarly`, taken by the engine client's first matching
 *     request, state/engine.tsx), instead of after the bundle has booted.
 * The build writes the chunk list; the dev server serves the script with an empty list.
 */
export const EDITOR_BOOT = 'editor-boot.js';
export function editorBootScript(chunks: readonly string[]): string {
	return `// Generated by apps/web/vite.config.ts (editorBoot). Preloads the editor and starts fetching the project.
(() => {
	const m = /^\\/project\\/([^/?#]+)/.exec(location.pathname);
	if (!m || m[1] === 'demo') return;
	for (const href of ${JSON.stringify(chunks)}) {
		const link = document.createElement('link');
		link.rel = 'modulepreload';
		link.href = href;
		document.head.appendChild(link);
	}
	let id;
	try {
		id = decodeURIComponent(m[1]);
	} catch {
		return;
	}
	const url = '/api/projects/' + encodeURIComponent(id);
	let response;
	try {
		response = fetch(url, { headers: { accept: 'application/json' } });
	} catch {
		return;
	}
	response.catch(() => undefined);
	window.__jasperEarly = { url, response, at: Date.now() };
})();
`;
}

export type BundleChunk = {
	type: string;
	fileName: string;
	facadeModuleId?: string | null;
	isEntry?: boolean;
	isDynamicEntry?: boolean;
	imports?: string[];
};

/** The chunks an editor URL needs beyond the entry's own: the shell, the panel bodies and what they import. */
export function editorChunks(bundle: Record<string, BundleChunk>): string[] {
	const chunks = Object.values(bundle).filter((c) => c.type === 'chunk');
	const byFile = new Map(chunks.map((c) => [c.fileName, c]));
	const closure = (start: BundleChunk[]) => {
		const seen = new Set<string>();
		const walk = (c: BundleChunk | undefined) => {
			if (!c || seen.has(c.fileName)) return;
			seen.add(c.fileName);
			for (const f of c.imports ?? []) walk(byFile.get(f));
		};
		for (const c of start) walk(c);
		return seen;
	};
	const norm = (id: string | null | undefined) => (id ?? '').replace(/\\/g, '/');
	const loaded = closure(chunks.filter((c) => c.isEntry));
	const editor = chunks.filter(
		(c) =>
			c.isDynamicEntry &&
			(/\/src\/shell\/EditorShell\.tsx$/.test(norm(c.facadeModuleId)) ||
				/\/src\/panels\/[^/]+\/[^/]+\.tsx$/.test(norm(c.facadeModuleId))),
	);
	return [...closure(editor)]
		.filter((f) => !loaded.has(f) && f.endsWith('.js'))
		.sort()
		.map((f) => `/${f}`);
}
