// Generates packages/project/src/registry/fx/premiere-stylize-distort-generate/video-font.ts.
// Printable ASCII (32…126) is rasterized with DejaVu Sans Mono Bold at 4×, box-downsampled
// to 12×20 and thresholded: 8 × 32-bit words per glyph, row-major, 12 bits per row, bit 0 = left.
// DejaVu fonts: Bitstream Vera / DejaVu licence (free to use and modify).
// pnpm tsx packages/compositions/test/fx-psdg/make-font.ts
import { existsSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { chromium } from '@playwright/test';

const here = dirname(fileURLToPath(import.meta.url));
const out = join(here, '../../../project/src/registry/fx/premiere-stylize-distort-generate/video-font.ts');
const W = 12;
const H = 20;
const S = 4;
const CHROME = [process.env.JASPER_BROWSER_EXECUTABLE, '/usr/bin/google-chrome', '/usr/bin/chromium'].find(
	(p): p is string => !!p && existsSync(p),
);
const browser = await chromium.launch({ executablePath: CHROME });
const page = await browser.newPage();
await page.setContent('<!doctype html><html><body></body></html>');
const words = (await page.evaluate(
	([w, h, s]) => {
		const c = document.createElement('canvas');
		c.width = w * s;
		c.height = h * s;
		const ctx = c.getContext('2d', { willReadFrequently: true })!;
		const result: number[] = [];
		for (let code = 32; code < 127; code++) {
			ctx.fillStyle = '#000';
			ctx.fillRect(0, 0, c.width, c.height);
			ctx.fillStyle = '#fff';
			ctx.font = `bold ${17.5 * s}px "DejaVu Sans Mono"`;
			ctx.textBaseline = 'alphabetic';
			const m = ctx.measureText(String.fromCharCode(code));
			ctx.fillText(String.fromCharCode(code), (w * s - m.width) / 2, 15.2 * s);
			const d = ctx.getImageData(0, 0, c.width, c.height).data;
			const bits: number[] = [];
			for (let y = 0; y < h; y++)
				for (let x = 0; x < w; x++) {
					let sum = 0;
					for (let j = 0; j < s; j++)
						for (let i = 0; i < s; i++) sum += d[((y * s + j) * c.width + x * s + i) * 4]!;
					bits.push(sum / (s * s * 255) > 0.42 ? 1 : 0);
				}
			for (let k = 0; k < 8; k++) {
				let v = 0;
				for (let b = 0; b < 32; b++) if (bits[k * 32 + b]) v = (v | (1 << b)) >>> 0;
				result.push(v >>> 0);
			}
		}
		return result;
	},
	[W, H, S] as const,
)) as number[];
await browser.close();
const lines: string[] = [];
for (let g = 0; g < 95; g++)
	lines.push(
		`  ${words
			.slice(g * 8, g * 8 + 8)
			.map((v) => `0x${v.toString(16)}u`)
			.join(', ')}`,
	);
const src = `// GENERATED by packages/compositions/test/fx-psdg/make-font.ts — do not edit. Bitmap font of the Video-bin text
// effects (family "premiere-stylize-distort-generate"): printable ASCII 32…126 rasterised from DejaVu Sans Mono Bold
// (Bitstream Vera / DejaVu licence) into ${W}×${H} 1-bit cells, 8 words per glyph (row-major, ${W} bits per row, bit 0 = left).
import type { GlslChunk } from '../shader.ts';

export const PSDG_FONT_CELL = { width: ${W}, height: ${H} } as const;

/** \`psdg_glyphBit(code, x, y)\`: the bit of character \`code\` (32…126) at cell pixel (x, y); 0 outside. */
export const GLSL_PSDG_FONT: GlslChunk = {
	name: 'psdg/font',
	source: /* glsl */ \`
const uint PSDG_FONT[${words.length}] = uint[${words.length}](
${lines.join(',\n')}
);
float psdg_glyphBit(int code, int x, int y) {
  if (code < 33 || code > 126 || x < 0 || y < 0 || x >= ${W} || y >= ${H}) return 0.0;
  int bit = y * ${W} + x;
  uint word = PSDG_FONT[(code - 32) * 8 + bit / 32];
  return float((word >> uint(bit % 32)) & 1u);
}
\`,
};
`;
writeFileSync(out, src);
console.log(`wrote ${out} (${words.length} words)`);
