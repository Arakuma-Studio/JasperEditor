// Class ids, property ids and definition ids of the AAF object model subset read and written (AAF Object
// Specification v1.1, AAF Edit Protocol). Class and data definition AUIDs are SMPTE labels (RP 224 / RP 210) in AUID
// byte order; property ids are the AAF / ST 377-1 local tags.
// Port of FilmCraft `crates/interchange/src/aaf/ids.rs` (MIT OR Apache-2.0).

/** AUID of a SMPTE universal label: the label's last 8 bytes become Data1–Data3 (little-endian), its first 8 Data4. */
export function ul(b: readonly number[]): Uint8Array {
	return Uint8Array.of(
		b[11]!,
		b[10]!,
		b[9]!,
		b[8]!,
		b[13]!,
		b[12]!,
		b[15]!,
		b[14]!,
		b[0]!,
		b[1]!,
		b[2]!,
		b[3]!,
		b[4]!,
		b[5]!,
		b[6]!,
		b[7]!,
	);
}

/** A GUID `{d1-d2-d3-d4}` in AUID byte order. */
export function guid(d1: number, d2: number, d3: number, d4: readonly number[]): Uint8Array {
	return Uint8Array.of(
		d1 & 0xff,
		(d1 >>> 8) & 0xff,
		(d1 >>> 16) & 0xff,
		(d1 >>> 24) & 0xff,
		d2 & 0xff,
		d2 >> 8,
		d3 & 0xff,
		d3 >> 8,
		...d4,
	);
}

